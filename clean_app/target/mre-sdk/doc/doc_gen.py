import re
import sys

def main():
    bindings_file = "target/armv5te-unknown-linux-gnueabi/release/build/mre-makefile-5a1297be16c3ee6f/out/bindings.rs"
    out_file = "/home/cipl1192/.gemini/antigravity-ide/brain/665ef9a7-f80f-42a7-8724-0e32fed1a51d/MRE_SDK_RUST_GUIDE.md"
    
    with open(bindings_file, "r") as f:
        content = f.read()

    # Extract all functions
    # e.g., pub fn vm_graphic_create_layer(x: VMINT, y: VMINT, width: VMINT, height: VMINT, trans_color: VMINT) -> VMINT;
    functions = re.findall(r'pub fn (vm_[a-zA-Z0-9_]+)\s*\(([^)]*)\)(.*?);', content)
    
    # Extract structures
    structs = re.findall(r'(pub struct (vm_[a-zA-Z0-9_]+)\s*\{[^\}]*\})', content, re.MULTILINE)

    # Extract constants
    constants = re.findall(r'pub const (VM_[a-zA-Z0-9_]+):.*?=.*?;', content)
    
    with open(out_file, "w") as out:
        out.write("# Exhaustive MRE SDK Rust Guide\n\n")
        out.write("This document provides a comprehensive, LLM-friendly guide on how to build MRE applications in Rust, covering **every single feature and API** of the SDK.\n\n")
        
        out.write("## 1. SDK Setup and Usage in Rust\n\n")
        out.write("To use the MRE SDK from Rust, your code must interface with the C FFI bindings generated by `bindgen`.\n\n")
        out.write("### Building the Application\n")
        out.write("1. **Cargo Configuration**: Ensure `Cargo.toml` specifies `crate-type = [\"staticlib\"]`.\n")
        out.write("2. **Target**: Build for ARM using `cargo build --target armv5te-unknown-linux-gnueabi --release`.\n")
        out.write("3. **Linker**: Use the existing MRE Makefile to link the resulting `.a` library with the SDK's C shims (`c_fix.c`, `gccmain.c`) and `.vxp` packager.\n\n")
        
        out.write("### Writing the Entry Point\n")
        out.write("The MRE system expects a `vm_main` C-compatible function. Define it as follows:\n")
        out.write("```rust\n")
        out.write("#[no_mangle]\n")
        out.write("pub extern \"C\" fn vm_main() {\n")
        out.write("    unsafe {\n")
        out.write("        vm_reg_sysevt_callback(Some(handle_sysevt));\n")
        out.write("        // register other callbacks...\n")
        out.write("    }\n")
        out.write("}\n")
        out.write("```\n\n")
        
        out.write("---\n\n")
        out.write("## 2. API Reference\n")
        out.write("The following sections list every function, argument, and structure available in the MRE SDK, translated to Rust.\n\n")
        
        out.write("### 2.1 Functions\n")
        for fn_name, args, ret in functions:
            ret_str = ret.strip()
            args_clean = args.replace('\n', ' ').strip()
            args_clean = re.sub(r'\s+', ' ', args_clean)
            out.write(f"#### `{fn_name}`\n")
            out.write(f"```rust\n")
            out.write(f"pub unsafe extern \"C\" fn {fn_name}({args_clean}){ret_str}\n")
            out.write(f"```\n")
            # Basic parsing of args for description
            arg_list = args_clean.split(',')
            if arg_list and arg_list[0]:
                out.write("**Arguments:**\n")
                for arg in arg_list:
                    arg = arg.strip()
                    if arg:
                        out.write(f"- `{arg}`\n")
            out.write("\n")
            
        out.write("### 2.2 Structures\n")
        for struct_body, struct_name in structs:
            # clean up struct body
            body_clean = re.sub(r'pub __bindgen_align: \[u\d+; \d+\],', '', struct_body)
            body_clean = re.sub(r'pub _bitfield_align_1: \[u\d+; \d+\],', '', body_clean)
            body_clean = re.sub(r'pub _bitfield_1: __BindgenBitfieldUnit<\[u8; \d+\], u\d+>,', '', body_clean)
            out.write(f"#### `{struct_name}`\n")
            out.write(f"```rust\n{body_clean}\n```\n\n")
            
        out.write("### 2.3 Constants (VM_...)\n")
        out.write("The SDK includes hundreds of constants prefix with `VM_`. Here is a comprehensive list of all constants available:\n\n")
        out.write("```rust\n")
        for const_name in constants:
            out.write(f"{const_name}\n")
        out.write("```\n")

if __name__ == "__main__":
    main()
